# - 1. Prompt builder - 
def build_judge_prompt(query, response, context, metric):
    """
    Build a prompt for LLM judge based on the query, response, context, and metric.
    
    Args:
        query (str): The original query or question.
        response (str): The response generated by the model.
        context (str): Additional context or information related to the query.
        metric (str): The evaluation metric to be used for judging the response."""
    
    base = f"""You are an expert evaluator for AI assistant responses.
Score the {metric.upper()} of the following response.

Query: {query}
Context: {context}
Response: {response}

"""
    if metric == "faithfulness":
        base += """FAITHFULNESS measures whether the response is 
grounded in the provided context without hallucinations.

Score 1-5:
5 = completely faithful to context
3 = mostly faithful, minor additions
1 = major hallucinations, contradicts context

Respond with ONLY valid JSON:
{"score": <1-5>, "reason": "<one sentence>"}"""

    elif metric == "relevancy":
        base += """RELEVANCY measures whether the response 
directly addresses what the query is asking.

Score 1-5:
5 = directly and completely answers the query
3 = partially answers the query
1 = does not answer the query at all

Respond with ONLY valid JSON:
{"score": <1-5>, "reason": "<one sentence>"}"""

    elif metric == "coherence":
        base += """COHERENCE measures whether the response 
is well-structured, clear, and logically consistent.

Score 1-5:
5 = perfectly clear and well-structured
3 = mostly clear, some awkward phrasing
1 = confusing, contradictory, or incoherent

Respond with ONLY valid JSON:
{"score": <1-5>, "reason": "<one sentence>"}"""

    return base

# - 2. Score parser -
def parse_score(llm_output: str) -> dict:
    """
    Extract score and reason from LLM response.
    Handles:
      - Clean JSON: {"score": 4, "reason": "..."}
      - JSON in markdown: ```json {...} ```
      - Fallback: regex search for score number
    """
    # Try 1: clean JSON parse
    try:
        result = json.loads(llm_output.strip())
        return {
            "score": float(result["score"]) / 5.0,  # normalize to 0-1
            "reason": result.get("reason", ""),
            "raw": llm_output
        }
    except:
        pass

    # Try 2: extract JSON from markdown code block
    try:
        match = re.search(r'```json\s*(.*?)\s*```', 
                         llm_output, re.DOTALL)
        if match:
            result = json.loads(match.group(1))
            return {
                "score": float(result["score"]) / 5.0,
                "reason": result.get("reason", ""),
                "raw": llm_output
            }
    except:
        pass

    # Try 3: regex fallback — find any number 1-5
    try:
        match = re.search(r'\b([1-5])\b', llm_output)
        if match:
            return {
                "score": float(match.group(1)) / 5.0,
                "reason": "extracted via regex fallback",
                "raw": llm_output
            }
    except:
        pass

    # Complete failure
    return {
        "score": None,
        "reason": "failed to parse",
        "raw": llm_output
    }

# - 3. MockLLM - 
class MockLLM:
    """
    Mock LLM for testing without API calls.
    Returns realistic scores based on simple heuristics.
    """
    def generate(self, prompt: str) -> str:
        # Check for hallucination keywords
        if "sony" in prompt.lower() and "dolby" in prompt.lower():
            return '{"score": 1, "reason": "Response contradicts context — Sony vs Dolby"}'
        elif "how do i" in prompt.lower() and "what is" in prompt.lower():
            return '{"score": 2, "reason": "Response answers wrong question type"}'
        else:
            return '{"score": 4, "reason": "Response is faithful and relevant"}'


# - 4. Single response judge - 
def judge_response(query, response, context, metric, llm):
    """Score one response using LLM-as-a-judge."""
    prompt = build_judge_prompt(query, response, context, metric)
    llm_output = llm.generate(prompt)
    result = parse_score(llm_output)
    return {
        "query":    query[:50],
        "metric":   metric,
        "score":    result["score"],
        "reason":   result["reason"],
        "pass":     result["score"] >= 0.6 if result["score"] else False
    }

# - 5. Batch judge -
def batch_judge(test_cases, metric, llm):
    """ Score all test cases and print summary"""
    results = []
    for tc in test_cases:
        result = judge_response(
            tc["query"], tc["response"], tc["context"], metric, llm
        )
        results.append(result)
    
        # Summary
    scores  = [r["score"] for r in results if r["score"]]
    passed  = sum(1 for r in results if r["pass"])

    print(f"\n{'='*55}")
    print(f"  LLM-as-Judge Report — metric: {metric.upper()}")
    print(f"{'='*55}")
    for r in results:
        status = "✅ PASS" if r["pass"] else "❌ FAIL"
        print(f"\n{r['query']}...")
        print(f"  Score : {r['score']:.2f}  {status}")
        print(f"  Reason: {r['reason']}")

    print(f"\n{'='*55}")
    print(f"  Pass rate : {passed}/{len(results)}")
    print(f"  Avg score : {np.mean(scores):.3f}")
    print(f"  Min score : {np.min(scores):.3f}")
    print(f"{'='*55}")
    return results


